function translateObjectsAndPhrases(text) {
  if (!text) return '';
  let result = text;

  phraseReplacements.forEach(item => {
    result = result.replace(item.regex, item.replacement);
  });

  const sortedIngIds = Object.keys(ingredientTranslations).sort((a, b) => b.length - a.length);
  sortedIngIds.forEach(id => {
    const pattern = id.replace(/-/g, '[-\\s]');
    const regex = new RegExp(`\\b${pattern}\\b`, 'gi');
    result = result.replace(regex, ingredientTranslations[id]);
  });

  result = result.replace(/\s+/g, ' ').trim();
  result = translateDigits(result);

  return result;
}

function translateCookingClause(clause) {
  let text = clause.trim();
  if (!text) return '';
  
  const leadingMatch = text.match(/^[^a-zA-Z0-9]+/);
  const trailingMatch = text.match(/[^a-zA-Z0-9]+$/);
  
  const leading = leadingMatch ? leadingMatch[0] : '';
  const trailing = trailingMatch ? trailingMatch[0] : '';
  
  let core = text.slice(leading.length, text.length - (trailingMatch ? trailing.length : 0)).trim();

  if (clauseDictionary[core.toLowerCase()]) {
    return leading + clauseDictionary[core.toLowerCase()] + trailing;
  }

  // Handle introductory prepositional phrases: "In a bowl, mix..." or "In same oil, add..."
  const introMatch = core.match(/^(in (?:a|the|same) [^,]+),\s*(.+)$/i);
  if (introMatch) {
    const introPart = translateObjectsAndPhrases(introMatch[1]);
    const actionPart = translateCookingClause(introMatch[2]);
    return leading + `${introPart}, ${actionPart}` + trailing;
  }

  // Check for leading adverbs like "Lightly slide in..."
  let adverbBn = '';
  for (const adv in leadingAdverbs) {
    if (core.toLowerCase().startsWith(adv + ' ')) {
      adverbBn = leadingAdverbs[adv];
      core = core.slice(adv.length).trim();
      break;
    }
  }

  // Check compound verbs first
  let verbEng = '';
  let verbBn = '';

  for (const cv of compoundVerbs) {
    if (core.toLowerCase().startsWith(cv.phrase)) {
      verbEng = cv.phrase;
      verbBn = cv.bn;
      break;
    }
  }

  // If not compound verb, check single-word verbs
  if (!verbEng) {
    const words = core.split(/\s+/);
    if (words.length > 0) {
      const firstWord = words[0].toLowerCase();
      if (verbs[firstWord]) {
        verbEng = firstWord;
        verbBn = verbs[firstWord];
      }
    }
  }

  if (verbEng) {
    let restOfClause = core.slice(verbEng.length).trim();
    let translatedRest = translateObjectsAndPhrases(restOfClause);

    let finalClause = '';
    if (translatedRest) {
      finalClause = adverbBn ? `${adverbBn} ${translatedRest} ${verbBn}` : `${translatedRest} ${verbBn}`;
    } else {
      finalClause = adverbBn ? `${adverbBn} ${verbBn}` : verbBn;
    }

    return leading + finalClause + trailing;
  }

  return leading + translateObjectsAndPhrases(core) + trailing;
}

export function translateSentence(text = '') {
  if (!text) return '';
  
  const trimmed = text.trim();

  // Note: Static recipe translations (titleBn, descriptionBn, culturalNoteBn) are
  // resolved by decorateRecipeTranslations() via recipe ID lookup.
  // This function handles dynamic clause-by-clause translation for content
  // without pre-existing curated translations.

  for (const id in cuisineTranslations) {
    const record = cuisineTranslations[id];
    if (record.descriptionBn && record.description && record.description.toLowerCase() === trimmed.toLowerCase()) {
      return record.descriptionBn;
    }
  }

  const parts = trimmed.split(/(\.|;|,?\s+and\s+|—|--)/i);
  
  const translatedParts = parts.map(part => {
    if (!part) return '';
    if (part.match(/^(\.|;|,?\s+and\s+|—|--)$/i)) {
      if (part.toLowerCase().includes('and')) {
        return ' এবং ';
      }
      if (part === '—' || part === '--') {
        return ' — ';
      }
      return part;
    }
    return translateCookingClause(part);
  });

  return translatedParts.join('').replace(/\s+/g, ' ').trim();
}

export function decorateRecipeTranslations(recipe) {
  if (!recipe) return null;

  const iconic = {
    ...(staticRecipeTranslations[recipe.id] || {}),
    ...(iconicRecipeTranslations[recipe.id] || {})
  };
  if (iconicRecipeTranslations[recipe.id]?.stepsBn) {
    iconic.stepsBn = iconicRecipeTranslations[recipe.id].stepsBn;
  }
  
  const titleBn = iconic?.titleBn || recipe.titleBn || translateSentence(recipe.title);
  const descriptionBn = iconic?.descriptionBn || recipe.descriptionBn || translateSentence(recipe.description);
  const culturalNoteBn = iconic?.culturalNoteBn || recipe.culturalNoteBn || translateSentence(recipe.culturalNote);

  const steps = (recipe.steps || []).map((step, idx) => {
    let instructionBn = '';
    if (iconic?.stepsBn && iconic.stepsBn[idx]) {
      instructionBn = iconic.stepsBn[idx];
    } else if (step.instructionBn && step.instructionBn.trim()) {
      instructionBn = step.instructionBn;
    } else {
      instructionBn = translateSentence(step.instruction);
    }
    return {
      ...step,
      instructionBn
    };
  });

  const ingredients = (recipe.ingredients || []).map(ing => {
    return {
      ...ing,
      nameBn: ingredientTranslations[ing.ingredientId] || ing.name || ing.ingredientId
    };
  });

  return {
    ...recipe,
    titleBn,
    descriptionBn,
    culturalNoteBn,
    steps,
    ingredients
  };
}
