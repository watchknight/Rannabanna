/**
 * Returns a high-res photograph for any ingredient.
 */
export function getIngredientImage(ingredientId, category = '') {
  if (!ingredientId) {
    if (category && CATEGORY_FALLBACK_IMAGES[category]) {
      return CATEGORY_FALLBACK_IMAGES[category];
    }
    return CATEGORY_FALLBACK_IMAGES['Vegetables'];
  }

  const cleanId = String(ingredientId).trim().toLowerCase();

  // 1. Direct match
  if (INGREDIENT_IMAGES[cleanId]) {
    return INGREDIENT_IMAGES[cleanId];
  }

  // Alias resolution for common variants
  const ALIAS_MAP = {
    'begun': 'eggplant',
    'aubergine': 'eggplant',
    'brinjal': 'eggplant',
    'ilish': 'hilsa-fish',
    'rui': 'rohita-fish',
    'chingri': 'shrimp',
    'prawn': 'shrimp',
    'prawns': 'shrimp',
    'curd': 'yogurt-plain',
    'dahi': 'yogurt-plain',
    'tok-doi': 'yogurt-plain',
    'doi': 'yogurt-plain',
    'mutton': 'mutton-cubes',
    'beef': 'beef-cubes',
    'chicken': 'chicken-breast',
    'cilantro': 'coriander-seed',
    'aloo': 'potato'
  };
  if (ALIAS_MAP[cleanId] && INGREDIENT_IMAGES[ALIAS_MAP[cleanId]]) {
    return INGREDIENT_IMAGES[ALIAS_MAP[cleanId]];
  }

  // 2. Normalized slug match
  const stripped = cleanId.replace(/[^a-z0-9-]/g, '');
  if (INGREDIENT_IMAGES[stripped]) {
    return INGREDIENT_IMAGES[stripped];
  }

  // 3. Substring match
  for (const [key, url] of Object.entries(INGREDIENT_IMAGES)) {
    if (stripped.includes(key) || key.includes(stripped)) {
      return url;
    }
  }

  // 4. Exact category fallback
  if (category && CATEGORY_FALLBACK_IMAGES[category]) {
    return CATEGORY_FALLBACK_IMAGES[category];
  }

  return CATEGORY_FALLBACK_IMAGES['Vegetables'];
}

/**
 * Returns an authentic culinary photograph for any recipe.
 * Guaranteed 100% authentic food photography coverage.
 */
export function getRecipeImage(recipeId, cuisineId = 'bengali') {
  if (!recipeId) {
    return CUISINE_IMAGES[cuisineId] || CUISINE_IMAGES['bengali'];
  }

  const cleanId = String(recipeId).trim().toLowerCase();

  // 1. Direct recipe key match
  if (RECIPE_IMAGES[cleanId]) {
    return RECIPE_IMAGES[cleanId];
  }

  // 2. Substring recipe match
  for (const [key, url] of Object.entries(RECIPE_IMAGES)) {
    if (cleanId.includes(key) || key.includes(cleanId)) {
      return url;
    }
  }

  // 3. Culinary Archetype match
  for (const [token, url] of Object.entries(CULINARY_ARCHETYPES)) {
    if (cleanId.includes(token)) {
      return url;
    }
  }

  // 4. Cuisine Cultural Banner Fallback
  if (cuisineId && CUISINE_IMAGES[cuisineId]) {
    return CUISINE_IMAGES[cuisineId];
  }

  return CUISINE_IMAGES['bengali'];
}

