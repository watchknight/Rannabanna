export const translatePreparation = (prep, lang) => {
  if (!prep || lang === "en") return prep;
  const trimmed = prep.trim();
  if (prepDictionary[trimmed]) return prepDictionary[trimmed];
  const lower = trimmed.toLowerCase();
  if (prepDictionary[lower]) return prepDictionary[lower];

  let res = trimmed;
  // Match longer keys first
  const keys = Object.keys(prepDictionary).sort((a, b) => b.length - a.length);
  for (const k of keys) {
    if (res.toLowerCase().includes(k.toLowerCase())) {
      const re = new RegExp(k.replace(/[.*+?^$${}()|[\]\\]/g, '\\$&'), 'gi');
      res = res.replace(re, prepDictionary[k]);
    }
  }
  return res;
};
